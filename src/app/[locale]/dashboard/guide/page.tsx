export default function GuidePage() {
  const [searchQuery, setSearchQuery] = useState("");
  const [expandedSections, setExpandedSections] = useState<Set<string>>(
    new Set(sections.map((s) => s.id)),
  );

  const toggleSection = (id: string) => {
    setExpandedSections((prev) => {
      const next = new Set(prev);
      if (next.has(id)) {
        next.delete(id);
      } else {
        next.add(id);
      }
      return next;
    });
  };

  const filteredSections = sections.filter(
    (section) =>
      !searchQuery ||
      section.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
      section.content.some((line) =>
        line.toLowerCase().includes(searchQuery.toLowerCase()),
      ),
  );

  return (
    <div className="mx-auto max-w-4xl py-6">
      <div className="mb-6">
        <div className="mb-2 flex items-center gap-3">
          <BookOpen className="size-8 text-primary" />
          <h1 className="text-2xl font-bold">Гарын авлага</h1>
        </div>
        <p className="text-muted-foreground">
          TOLOM авто засварын удирдлагын системийг ашиглах заавар
        </p>
      </div>

      <div className="relative mb-6">
        <Search className="absolute left-3 top-1/2 size-4 -translate-y-1/2 text-muted-foreground" />
        <Input
          placeholder="Хайх..."
          value={searchQuery}
          onChange={(e) => setSearchQuery(e.target.value)}
          className="pl-9"
        />
      </div>

      <div className="space-y-3">
        {filteredSections.map((section) => (
          <div
            key={section.id}
            className="rounded-lg border bg-card text-card-foreground shadow-sm"
          >
            <button
              onClick={() => toggleSection(section.id)}
              className="flex w-full items-center justify-between px-4 py-3 text-left font-medium hover:bg-accent/50 rounded-t-lg"
            >
              <span>{section.title}</span>
              {expandedSections.has(section.id) ? (
                <ChevronUp className="size-4 text-muted-foreground" />
              ) : (
                <ChevronDown className="size-4 text-muted-foreground" />
              )}
            </button>
            {expandedSections.has(section.id) && (
              <div className="border-t px-4 py-3 space-y-2 text-sm text-muted-foreground">
                {section.content.map((line, idx) => {
                  if (line === "") {
                    return <br key={idx} />;
                  }
                  if (line.startsWith("• ")) {
                    return (
                      <p key={idx} className="ml-2">
                        {line}
                      </p>
                    );
                  }
                  if (line.endsWith(":")) {
                    return (
                      <p key={idx} className="font-medium text-foreground">
                        {line}
                      </p>
                    );
                  }
                  return <p key={idx}>{line}</p>;
                })}
              </div>
            )}
          </div>
        ))}
      </div>

      {filteredSections.length === 0 && (
        <div className="py-12 text-center text-muted-foreground">
          <p>Илэрц олдсонгүй</p>
        </div>
      )}
    </div>
  );
}
