#!/usr/bin/env node

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();
const outputPath = join(root, ".agents", "package-index.md");
const checkOnly = process.argv.includes("--check");

function readJson(path) {
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

function normalizeRepository(repository) {
  if (!repository) return "";
  const value = typeof repository === "string" ? repository : repository.url;
  if (!value) return "";
  const normalized = value
    .replace(/^git\+/, "")
    .replace(/^git@github\.com:/, "https://github.com/")
    .replace(/^git:\/\/github\.com\//, "https://github.com/")
    .replace(/^ssh:\/\/git@github\.com\//, "https://github.com/")
    .replace(/^github:/, "https://github.com/")
    .replace(/\.git$/, "");
  return /^https?:\/\/\S+$/.test(normalized)
    ? normalized
    : /^[\w.-]+\/[\w.-]+$/.test(normalized)
      ? `https://github.com/${normalized}`
      : "";
}

function normalizeHomepage(homepage) {
  return typeof homepage === "string" && /^https?:\/\/\S+$/.test(homepage)
    ? homepage
    : "";
}

function packagePath(name) {
  return `node_modules/${name}`;
}

function relativePackageFile(name, file) {
  return file ? `${packagePath(name)}/${file}` : "not declared";
}

function packageMetadata(name, entry) {
  const metadata = readJson(join(entry.path, "package.json")) ?? {};
  const types = metadata.types ?? metadata.typings ?? "";
  const main = metadata.module ?? metadata.main ?? "";
  const repository = normalizeRepository(metadata.repository);
  const homepage = normalizeHomepage(metadata.homepage);
  const docs = homepage || repository;
  const readme = existsSync(join(entry.path, "README.md"))
    ? relativePackageFile(name, "README.md")
    : "not found";

  return {
    name,
    requested: entry.requested ?? "not declared",
    resolved: entry.version ?? "unknown",
    local: packagePath(name),
    readme,
    types: relativePackageFile(name, types),
    entrypoint: relativePackageFile(name, main),
    docs: docs || "not declared in package metadata",
    repository: repository || "not declared in package metadata",
  };
}

function fingerprint(path) {
  if (!existsSync(path)) return "missing";
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

const packageJson = readJson(join(root, "package.json"));
if (!packageJson) {
  console.error("agent:docs:index: package.json not found");
  process.exit(1);
}

const lockfilePath = join(root, "pnpm-lock.yaml");
const lockfileFingerprint = fingerprint(lockfilePath);
let installed;

try {
  installed = JSON.parse(
    execFileSync("pnpm", ["list", "--depth=0", "--json"], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    }),
  )[0];
} catch (error) {
  console.error("agent:docs:index: pnpm list failed");
  console.error(error.stderr?.toString().trim() || error.message);
  process.exit(1);
}

const requested = {
  ...packageJson.dependencies,
  ...packageJson.devDependencies,
  ...packageJson.optionalDependencies,
};
const entries = [
  ...Object.entries(installed?.dependencies ?? {}),
  ...Object.entries(installed?.devDependencies ?? {}),
];
const packages = entries
  .map(([name, entry]) => packageMetadata(name, { ...entry, requested: requested[name] }))
  .sort((a, b) => a.name.localeCompare(b.name));

const generatedAt = new Date().toISOString();
const lines = [
  "# Package Evidence Index",
  "",
  "Generated by `pnpm agent:docs:index`. This is a navigation map, not a substitute for exact-version documentation.",
  "",
  `generated_at: ${generatedAt}`,
  `lockfile: pnpm-lock.yaml`,
  `lockfile_sha256: ${lockfileFingerprint}`,
  `package_count: ${packages.length}`,
  "",
  "| Package | Requested | Resolved | Local artifacts | Official docs/source |",
  "| --- | --- | --- | --- | --- |",
  ...packages.map((pkg) => {
    const artifacts = [
      `README: \`${pkg.readme}\``,
      `types: \`${pkg.types}\``,
      `entry: \`${pkg.entrypoint}\``,
    ].join("<br>");
    const official = [
      pkg.docs === "not declared in package metadata" ? pkg.docs : `[docs](${pkg.docs})`,
      pkg.repository === "not declared in package metadata" ? pkg.repository : `[source](${pkg.repository})`,
    ].join("<br>");
    return `| \`${pkg.name}\` | \`${pkg.requested}\` | \`${pkg.resolved}\` | ${artifacts} | ${official} |`;
  }),
  "",
  "## Evidence policy",
  "",
  "Use the resolved version from `pnpm-lock.yaml` for normal feature work. Read local package artifacts and exact-version official docs before using an API. Use Context7 only with the exact version; fall back to local types/source and official release notes when retrieval fails or conflicts.",
];

const output = `${lines.join("\n")}\n`;

if (checkOnly) {
  if (!existsSync(outputPath)) {
    console.error(`agent:docs:index: missing ${relative(root, outputPath)}`);
    process.exit(1);
  }
  const existing = readFileSync(outputPath, "utf8").replace(
    /^generated_at: .*$/m,
    "generated_at: <ignored>",
  );
  const expected = output.replace(/^generated_at: .*$/m, "generated_at: <ignored>");
  if (existing !== expected) {
    console.error(`agent:docs:index: stale ${relative(root, outputPath)}`);
    process.exit(1);
  }
  console.log(`agent:docs:index: OK (${packages.length} packages, ${lockfileFingerprint})`);
  process.exit(0);
}

const directory = join(root, ".agents");
if (!existsSync(directory)) {
  execFileSync("mkdir", ["-p", directory], { cwd: root });
}
writeFileSync(outputPath, output);
console.log(`agent:docs:index: wrote ${relative(root, outputPath)} (${packages.length} packages)`);
