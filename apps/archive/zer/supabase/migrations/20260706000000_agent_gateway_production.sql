CREATE INDEX IF NOT EXISTS idx_agent_sessions_org
  ON public.agent_sessions (organization_id);
CREATE INDEX IF NOT EXISTS idx_agent_sessions_updated
  ON public.agent_sessions (updated_at);

ALTER TABLE public.agent_sessions ENABLE ROW LEVEL SECURITY;

-- Daily token spend tracking with atomic increments.
CREATE TABLE IF NOT EXISTS public.agent_daily_spend (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  date DATE NOT NULL,
  tokens_used BIGINT NOT NULL DEFAULT 0,
  api_calls INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (organization_id, date)
);

CREATE INDEX IF NOT EXISTS idx_agent_daily_spend_org_date
  ON public.agent_daily_spend (organization_id, date);

ALTER TABLE public.agent_daily_spend ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.increment_daily_spend(
  p_org_id UUID,
  p_date DATE,
  p_tokens BIGINT
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.agent_daily_spend (organization_id, date, tokens_used, api_calls)
  VALUES (p_org_id, p_date, p_tokens, 1)
  ON CONFLICT (organization_id, date)
  DO UPDATE SET
    tokens_used = public.agent_daily_spend.tokens_used + p_tokens,
    api_calls = public.agent_daily_spend.api_calls + 1,
    updated_at = now();
END;
$$;

REVOKE ALL ON FUNCTION public.increment_daily_spend(UUID, DATE, BIGINT) FROM PUBLIC;

