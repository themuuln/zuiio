/**
 * Returns the industry preset for a given business type.
 * Falls back to general_repair if the type is unrecognized.
 */
export function getPreset(type: string): IndustryPreset {
  if (type in INDUSTRY_PRESETS) {
    return INDUSTRY_PRESETS[type as BusinessType];
  }
  return INDUSTRY_PRESETS.general_repair;
}

/**
 * Returns the label i18n key for a given business type.
 * Falls back to general_repair if the type is unrecognized.
 */
export function getBusinessTypeLabel(type: string): string {
  return getPreset(type).labelKey;
}

/**
 * Returns the list of all supported business types.
 */
export function getBusinessTypes(): readonly BusinessType[] {
  return BUSINESS_TYPES;
}

/**
 * Returns the default service names for a given business type.
 * Falls back to general_repair if the type is unrecognized.
 */
export function getDefaultServices(type: string): string[] {
  return getPreset(type).defaultServices.map((s) => s.name);
}

/**
 * Returns the default diagnosis label names for a given business type.
 * Falls back to general_repair if the type is unrecognized.
 */
export function getDefaultDiagnosisLabels(type: string): string[] {
  return getPreset(type).defaultDiagnosisLabels.map((l) => l.name);
}
