// ── Business Type Presets ─────────────────────────────────────
// Each preset configures default services, parts, diagnosis labels,
// and thresholds tailored to the type of auto shop. Seeded into a
// new organization's catalogs at signup.
//
// Data conventions:
//  - `name` is the canonical English name; `nameMn` is Mongolian.
//  - `category` values follow the org-level catalog convention
//    (Mongolian) so category filters group like items together.
//  - `default_price` is a realistic MNT reference price — orgs
//    always adjust it, but a non-zero start beats an empty catalog.
//  - `servicePartSuggestions` pairs each service with the parts a
//    shop typically sells alongside it (seeded into
//    service_part_suggestions so Bay View can speed up ordering).

export const BUSINESS_TYPES = [
  "general_repair",
  "tire_shop",
  "body_shop",
  "dealership",
  "fleet",
  "quick_lube",
] as const;

export type BusinessType = (typeof BUSINESS_TYPES)[number];

export interface PresetService {
  /** Canonical English name */
  name: string;
  /** Mongolian name (shown when locale=mn) */
  nameMn: string;
  /** Catalog category (Mongolian, matches org-level convention) */
  category: string;
  /** Optional short description */
  description?: string;
  /** Estimated labor time in minutes */
  estimatedDurationMinutes?: number;
  /** Recommended service interval in months */
  intervalMonths?: number | null;
  /** Recommended service interval in km */
  intervalKm?: number | null;
  /** Reference default price in MNT */
  defaultPrice?: number;
}

export interface PresetDiagnosisLabel {
  name: string;
  nameMn: string;
}

export interface PresetPart {
  /** Canonical English name */
  name: string;
  /** Mongolian name (shown when locale=mn) */
  nameMn: string;
  /** Common part number (nullable — many parts are universal) */
  partNumber?: string | null;
  /** Part category */
  category: string;
  /** Sales unit: piece/set/liter/container/etc. */
  unit?: string;
  /** Reference default price in MNT */
  defaultPrice?: number;
}

export interface PresetSuggestion {
  /** Service name — must match a PresetService.name in the same preset */
  service: string;
  /** Part name — must match a PresetPart.name in the same preset */
  part: string;
  /** Quantity of the part used per unit of service */
  quantity: number;
  /** Optional note shown to the mechanic */
  notes?: string;
}

export interface IndustryPreset {
  /** i18n key for the business type label */
  labelKey: string;
  /** i18n key for the business type description */
  descriptionKey: string;
  /** Default services seeded into the service catalog */
  defaultServices: PresetService[];
  /** Default diagnosis labels seeded into diagnosis_labels */
  defaultDiagnosisLabels: PresetDiagnosisLabel[];
  /** Default parts seeded into the parts catalog */
  defaultParts: PresetPart[];
  /** Service → part suggestions seeded into service_part_suggestions */
  servicePartSuggestions: PresetSuggestion[];
  /** Minimum stock threshold (parts) */
  defaultThreshold: number;
}

