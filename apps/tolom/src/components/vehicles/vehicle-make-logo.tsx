/* ── Public component ─────────────────────────────────────────── */

interface VehicleMakeLogoProps {
  make: string | null | undefined;
  className?: string;
  /** Forwarded to icon SVG width/height. */
  size?: number | string;
}

export function VehicleMakeLogo({
  make,
  className,
  size,
}: VehicleMakeLogoProps) {
  const key = make?.toLowerCase().trim() ?? "";
  const sizes = size ? undefined : cn("size-5", className);

  // 1. Inline brand SVG icons
  const Icon = LOGO_MAP[key];
  if (Icon)
    return <Icon className={sizes ?? className} width={size} height={size} />;

  // 2. SVG fallbacks (Lexus, Genesis, Land Rover)
  const Fallback = SVG_FALLBACKS[key];
  if (Fallback)
    return (
      <Fallback
        className={sizes ?? className}
        style={size ? { width: size, height: size } : undefined}
      />
    );

  // 3. Letter fallback
  return (
    <DefaultLogo
      make={key}
      className={sizes ?? className}
      style={size ? { width: size, height: size } : undefined}
    />
  );
}
