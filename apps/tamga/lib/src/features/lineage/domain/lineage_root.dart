class LineageRoot {
  const LineageRoot({
    required this.id,
    required this.name,
    required this.coat,
    required this.birthYear,
    required this.offspringCount,
    required this.awardCount,
    required this.notes,
  });

  final String id;
  final String name;
  final String coat;
  final int birthYear;
  final int offspringCount;
  final int awardCount;
  final String notes;
}
