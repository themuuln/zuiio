/// Худалдах гэрээ (Bill of Sale) домэйн загвар.
///
/// Зарын мэдээлэл, худалдагч/худалдан авагчийн мэдээлэл, үнэ,
/// огноо, нөхцөлүүдийг багтаасан гэрээний баримт.
class MarketContract {
  const MarketContract({
    required this.id,
    required this.listingId,
    required this.horseName,
    this.horseDescription,
    required this.sellerName,
    required this.buyerName,
    required this.price,
    required this.currency,
    required this.date,
    this.terms = _defaultTerms,
  });

  /// Гэрээний ID.
  final String id;

  /// Зарын ID.
  final String listingId;

  /// Морины нэр.
  final String horseName;

  /// Морины дэлгэрэнгүй мэдээлэл.
  final String? horseDescription;

  /// Худалдагчийн нэр.
  final String sellerName;

  /// Худалдан авагчийн нэр.
  final String buyerName;

  /// Үнэ.
  final int price;

  /// Валют (MNT, USD, etc.).
  final String currency;

  /// Гэрээний огноо.
  final DateTime date;

  /// Нөхцөлүүд.
  final List<String> terms;

  /// Форматлагдсан үнэ.
  String get formattedPrice {
    final formatted = price.toString().replaceAllMapped(
      RegExp(r'\B(?=(\d{3})+(?!\d))'),
      (match) => ',',
    );
    return '$formatted $currency';
  }

  /// Форматлагдсан огноо.
  String get formattedDate =>
      '${date.year}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}';

  /// Гэрээний текстийг буцаах.
  String toPlainText() {
    final buf = StringBuffer();
    buf.writeln('═══════════════════════════════════════════');
    buf.writeln('         ХУДАЛДААНЫ ГЭРЭЭ / BILL OF SALE');
    buf.writeln('═══════════════════════════════════════════');
    buf.writeln('');
    buf.writeln('Огноо / Date: $formattedDate');
    buf.writeln('Гэрээний дугаар / Contract #: $id');
    buf.writeln('');
    buf.writeln('--- Мэдээлэл / Details ---');
    buf.writeln('Морь / Horse: $horseName');
    if (horseDescription != null && horseDescription!.isNotEmpty) {
      buf.writeln('Тайлбар / Description: $horseDescription');
    }
    buf.writeln('');
    buf.writeln('--- Талууд / Parties ---');
    buf.writeln('Худалдагч / Seller: $sellerName');
    buf.writeln('Худалдан авагч / Buyer: $buyerName');
    buf.writeln('');
    buf.writeln('--- Үнэ / Price ---');
    buf.writeln('Үнэ / Price: $formattedPrice');
    buf.writeln('');
    buf.writeln('--- Нөхцөлүүд / Terms & Conditions ---');
    for (var i = 0; i < terms.length; i++) {
      buf.writeln('${i + 1}. ${terms[i]}');
    }
    buf.writeln('');
    buf.writeln('═══════════════════════════════════════════');
    buf.writeln('  ТАМГА ХХК-ийн үүсгэсэн / Generated by Tamga LLC');
    buf.writeln('═══════════════════════════════════════════');
    return buf.toString();
  }

  /// Default terms for the contract.
  static const _defaultTerms = [
    'Морь дээрх бүх эрх худалдан авагчид шилжинэ / All rights of the horse transfer to the buyer.',
    'Морийг хүлээлгэн өгсөнөөс хойшхи бүх хариуцлага худалдан авагчид шилжинэ / After handover, all responsibility transfers to the buyer.',
    'Морины эрүүл мэндийн байдлыг талууд хүлээн зөвшөөрсөн / Both parties acknowledge the health condition of the horse.',
    'Энэхүү гэрээ нь цахим хэлбэрээр үйлчилнэ / This contract is valid in electronic form.',
  ];

  // ── CopyWith ──────────────────────────────────────────────────

  MarketContract copyWith({
    String? id,
    String? listingId,
    String? horseName,
    Object? horseDescription = _sentinel,
    String? sellerName,
    String? buyerName,
    int? price,
    String? currency,
    DateTime? date,
    List<String>? terms,
  }) {
    return MarketContract(
      id: id ?? this.id,
      listingId: listingId ?? this.listingId,
      horseName: horseName ?? this.horseName,
      horseDescription: horseDescription == _sentinel
          ? this.horseDescription
          : horseDescription as String?,
      sellerName: sellerName ?? this.sellerName,
      buyerName: buyerName ?? this.buyerName,
      price: price ?? this.price,
      currency: currency ?? this.currency,
      date: date ?? this.date,
      terms: terms ?? this.terms,
    );
  }

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is MarketContract &&
          runtimeType == other.runtimeType &&
          id == other.id &&
          listingId == other.listingId &&
          horseName == other.horseName &&
          horseDescription == other.horseDescription &&
          sellerName == other.sellerName &&
          buyerName == other.buyerName &&
          price == other.price &&
          currency == other.currency &&
          date == other.date;

  @override
  int get hashCode => Object.hash(
      id, listingId, horseName, horseDescription,
      sellerName, buyerName, price, currency, date);

  @override
  String toString() =>
      'MarketContract(id: $id, listingId: $listingId, horseName: $horseName, price: $price)';
}

const _sentinel = Object();
