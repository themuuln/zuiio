/**
 * Write Engine type definitions.
 *
 * The Write Engine mirrors the Read Engine. It replaces the inline,
 * hardcoded per-product write tools (createWorkOrder, createSale, …) with ONE
 * dynamic `writeData` tool. The LLM emits a WritePlan → the engine validates it
 * against a ProductCatalog (field existence, required fields, enum/type checks) →
 * compiles to a Supabase mutation → executes with tenant isolation enforced.
 *
 * Tenant isolation: `organization_id` is NEVER accepted from the LLM. The engine
 * injects it at compile time and re-applies it on update/delete so a write can
 * never touch another org's rows.
 *
 * Field/tenant metadata is intentionally shared with the Read Engine: a write
 * catalog is a subset of the same `ProductCatalog` shape (datasets + fields +
 * tenant), so we reuse those types rather than redefining them.
 */

import type { SupabaseClient } from "@supabase/supabase-js";
import type { ProductCatalog } from "@/read-engine/types";

// ─── Write Catalog ──────────────────────────────────────────────────────────

/**
 * A write catalog describes which datasets are writable and how.
 *
 * It is a projection of the product's `ProductCatalog`: the same `datasets`
 * (with the same `Field` definitions) and the same `tenant` config. The
 * `writable` flag on each dataset marks which tables the agent may mutate.
 *
 * Reusing `ProductCatalog` keeps reads and writes consistent: a field that is
 * `dimension`/`measures` in reads is the same column the agent writes to.
 */
export interface WriteCatalog {
	/** Unique product identifier. Must match the read catalog id. */
	id: string;
	/** Product name in Mongolian. */
	name: string;
	/** Tenant isolation config (same as read catalog). */
	tenant: ProductCatalog["tenant"];
	/** Writable datasets, keyed by ID. Subset of the read catalog's datasets. */
	datasets: Record<string, WritableDataset>;
}

/** A dataset the agent is allowed to mutate. */
export interface WritableDataset {
	/** PostgREST table name. Maps to supabase.from({source}). */
	source: string;
	/** Dataset name in Mongolian. */
	displayName: string;
	/** Whether inserts are allowed. */
	insertable: boolean;
	/** Whether updates by PK are allowed. */
	updatable: boolean;
	/** Whether soft/hard deletes are allowed. */
	deletable: boolean;
	/** Column definitions. Reuses the read catalog Field shape. */
	fields: Record<string, WriteField>;
	/** Primary key column name (for update/delete targeting). */
	pk: string;
}

/** Column definition for writes. Reuses the read-engine Field shape. */
export interface WriteField {
	/** Postgres-compatible type. Used for type coercion checks. */
	type: ProductCatalog["datasets"][string]["fields"][string]["type"];
	/** Whether the agent MUST supply this field on insert. */
	required?: boolean;
	/**
	 * Whether the agent may write this field. Columns the agent must never
	 * set (organization_id, deleted_at) are writable: false.
	 */
	writable?: boolean;
	/** Allowed values for enum-like columns (status, type, …). */
	allowedValues?: readonly string[];
}

// ─── Write Plan (LLM Output) ────────────────────────────────────────────────

/**
 * Structured mutation plan emitted by the LLM as the `writeData` tool argument.
 * One plan = one operation on one dataset (the agent issues multiple plans for
 * multi-step flows like "create customer then create work order").
 */
export interface WritePlan {
	/** Dataset ID to mutate. Must exist in the write catalog. */
	dataset: string;
	/** Mutation kind. */
	operation: WriteOperationKind;
	/**
	 * Target row PK for update/delete. Required for those operations.
	 * Never required for insert (the DB assigns the PK).
	 */
	id?: string;
	/**
	 * Column → value map for insert/update.
	 * The engine strips non-writable fields and injects organization_id.
	 */
	data?: Record<string, unknown>;
	/**
	 * Soft-delete flag. When true and the dataset supports it, the engine
	 * sets `deleted_at = now()` instead of hard-deleting the row.
	 * Default: true (prefer soft delete).
	 */
	softDelete?: boolean;
}

/** Mutation kinds supported by the Write Engine. */
export type WriteOperationKind = "insert" | "update" | "delete";

// ─── Compiled Mutation ──────────────────────────────────────────────────────

/**
 * A compiled Supabase mutation, ready to execute.
 * Generated by the compiler from WritePlan + WriteCatalog + tenantId.
 */
export interface CompiledMutation {
	/** PostgREST table. */
	source: string;
	/** Mutation kind. */
	operation: WriteOperationKind;
	/** Target row PK (update/delete). */
	id?: string;
	/** Final column → value map, with organization_id injected and non-writable fields stripped. */
	payload: Record<string, unknown>;
	/** Whether to soft-delete (set deleted_at) instead of hard delete. */
	softDelete: boolean;
	/** Resolved tenant ID (for audit logging). */
	tenantId: string;
	/** Human-readable description (Mongolian) for debugging. */
	description: string;
}

// ─── Engine Configuration ───────────────────────────────────────────────────

/** Runtime config for the Write Engine. Resolved once per request. */
export interface WriteEngineConfig {
	/** Tenant/org ID from JWT. NEVER from LLM input. */
	tenantId: string;
	/** The write catalog for this request's product. */
	catalog: WriteCatalog;
	/** Supabase client for execution. */
	supabase: SupabaseClient;
}

// ─── Engine Result ──────────────────────────────────────────────────────────

/** Outcome of a single write operation. */
export interface WriteResult {
	/** Whether the mutation succeeded. */
	success: boolean;
	/** Human-readable Mongolian message for the LLM/user. */
	message: string;
	/** The affected row's id (insert → new id, update/delete → target id). */
	id?: string;
	/** The returned row (insert/update select), if any. */
	data?: Record<string, unknown>;
	/** Non-fatal warnings (e.g., stripped non-writable field). */
	warnings?: string[];
}

// ─── Validation ─────────────────────────────────────────────────────────────

/** Validation error from Write Plan → Catalog validation. */
export interface WritePlanValidationError {
	code: WriteValidationErrorCode;
	message: string;
	field?: string;
}

/** Validation error codes. */
export type WriteValidationErrorCode =
	| "DATASET_NOT_WRITABLE"
	| "DATASET_NOT_FOUND"
	| "OPERATION_NOT_ALLOWED"
	| "MISSING_ID"
	| "MISSING_DATA"
	| "FIELD_NOT_FOUND"
	| "FIELD_NOT_WRITABLE"
	| "FIELD_REQUIRED"
	| "INVALID_ENUM_VALUE"
	| "INVALID_TYPE"
	| "TENANT_COLUMN_LEAKED";
